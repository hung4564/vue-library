const SUBPATH_MODULES: Record<
  keyof typeof MAP_DATASET_SUBPATH_RUNTIME_EXPORTS,
  Record<string, unknown>
> = {
  geojson: geojsonApi,
  'data-management': dataManagementApi,
  'attribute-table': attributeTableApi,
  raster: rasterApi,
  'vector-tile': vectorTileApi,
  identify: identifyApi,
  menu: menuApi,
  style: styleApi,
  'create-control': createControlApi,
  'geo-export': geoExportApi,
};

describe('public API surface', () => {
  it('root runtime exports match Stable + Experimental allowlists', () => {
    const keys = Object.keys(api).sort();
    const expected = [
      ...MAP_DATASET_STABLE_RUNTIME_EXPORTS,
      ...MAP_DATASET_EXPERIMENTAL_RUNTIME_EXPORTS,
    ].sort();
    expect(keys).toEqual(expected);
  });

  it.each(
    Object.keys(MAP_DATASET_SUBPATH_RUNTIME_EXPORTS) as Array<
      keyof typeof MAP_DATASET_SUBPATH_RUNTIME_EXPORTS
    >,
  )('subpath entry `%s` runtime exports match the allowlist', (name) => {
    const keys = Object.keys(SUBPATH_MODULES[name]).sort();
    const expected = [...MAP_DATASET_SUBPATH_RUNTIME_EXPORTS[name]].sort();
    expect(keys).toEqual(expected);
  });

  it('root entry does not re-export domain symbols', () => {
    /** Intentional root re-exports for data-management consumers. */
    const allowedOverlap = new Set([
      'createDataManagement',
      'isDataManagementView',
    ]);
    const rootKeys = new Set(Object.keys(api));
    const overlap: string[] = [];
    for (const names of Object.values(MAP_DATASET_SUBPATH_RUNTIME_EXPORTS)) {
      for (const name of names) {
        if (rootKeys.has(name) && !allowedOverlap.has(name)) {
          overlap.push(name);
        }
      }
    }
    expect(overlap).toEqual([]);
  });
});
